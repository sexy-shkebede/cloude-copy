def mesh_edges(points: np.ndarray) -> list[tuple[int, int]]:
    """Рёбра триангуляции Делоне по 68 точкам (для эффекта «сетки»)."""
    import cv2

    pts = np.asarray(points, np.float32)
    x0, y0 = pts.min(0) - 10
    x1, y1 = pts.max(0) + 10
    subdiv = cv2.Subdiv2D((int(x0), int(y0), int(x1 - x0) + 1, int(y1 - y0) + 1))
    for p in pts:
        subdiv.insert((float(p[0]), float(p[1])))
    edges = set()
    lookup = {(round(float(p[0]), 2), round(float(p[1]), 2)): i for i, p in enumerate(pts)}

    def idx(x, y):
        return lookup.get((round(float(x), 2), round(float(y), 2)))

    for t in subdiv.getTriangleList():
        ids = [idx(t[0], t[1]), idx(t[2], t[3]), idx(t[4], t[5])]
        if None in ids:
            continue
        for a, b in ((0, 1), (1, 2), (2, 0)):
            e = tuple(sorted((ids[a], ids[b])))
            edges.add(e)
    return sorted(edges)


def catmull_rom(points: list[tuple[float, float]], samples: int = 12) -> np.ndarray:
    p = np.asarray(points, np.float32)
    p = np.vstack([p[0], p, p[-1]])
    out = []
    for i in range(1, len(p) - 2):
        p0, p1, p2, p3 = p[i - 1], p[i], p[i + 1], p[i + 2]
        for t in np.linspace(0, 1, samples, endpoint=False):
            t2, t3 = t * t, t * t * t
            out.append(
                0.5
                * (
                    2 * p1
                    + (-p0 + p2) * t
                    + (2 * p0 - 5 * p1 + 4 * p2 - p3) * t2
                    + (-p0 + 3 * p1 - 3 * p2 + p3) * t3
                )
            )
    out.append(p[-2])
    return np.array(out, np.float32)


